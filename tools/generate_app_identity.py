#!/usr/bin/env python3
"""Generate platform identity files from app.properties without platform SDKs."""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


@dataclass(frozen=True)
class AppIdentity:
    name: str
    version: str
    build: int
    android_id: str
    apple_id: str
    repository: str
    upstream: str
    source_release_url: str | None = None


def read_identity(path: Path) -> AppIdentity:
    values = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or key in values:
            raise ValueError(f"Invalid or duplicate property: {key}")
        values[key] = value
    expected = {"app.name", "app.version", "app.build", "app.androidId", "app.appleId", "app.repository", "app.upstream"}
    unexpected_or_missing = (set(values) - {"app.sourceReleaseUrl"}) ^ expected
    if unexpected_or_missing:
        raise ValueError(f"Unexpected or missing properties: {sorted(unexpected_or_missing)}")
    if not values["app.name"] or any(ch in values["app.name"] for ch in '\n\r$=;'):
        raise ValueError("Application name must be a nonempty single-line literal")
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", values["app.version"]):
        raise ValueError("Version must have three numeric components")
    if not values["app.build"].isdigit() or not 1 <= int(values["app.build"]) <= 2_100_000_000:
        raise ValueError("Build must be a positive Android-compatible integer")
    for key in ("app.androidId", "app.appleId"):
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+", values[key]):
            raise ValueError(f"Invalid application identifier: {key}")
    for key in ("app.repository", "app.upstream"):
        if not values[key].startswith("https://") or any(ch.isspace() for ch in values[key]):
            raise ValueError(f"Expected an HTTPS URL: {key}")
    source_url = values.get("app.sourceReleaseUrl") or None
    if source_url:
        url = urlsplit(source_url)
        if url.scheme != "https" or not url.hostname or url.username is not None or any(ch.isspace() for ch in source_url):
            raise ValueError("Expected an HTTPS URL without credentials: app.sourceReleaseUrl")
    return AppIdentity(values["app.name"], values["app.version"], int(values["app.build"]),
                       values["app.androidId"], values["app.appleId"], values["app.repository"],
                       values["app.upstream"], source_url)


def generated_files(identity: AppIdentity) -> dict[str, bytes]:
    quoted = lambda value: json.dumps(value, ensure_ascii=False).replace("$", r"\$")
    kotlin = f'''// Generated by tools/generate_app_identity.py from app.properties.
package dev.logisim.mobile

object AppIdentity {{
    const val name: String = {quoted(identity.name)}
    const val version: String = {quoted(identity.version)}
    const val build: Int = {identity.build}
    const val androidId: String = {quoted(identity.android_id)}
    const val appleId: String = {quoted(identity.apple_id)}
    const val repository: String = {quoted(identity.repository)}
    const val upstream: String = {quoted(identity.upstream)}
    val sourceReleaseUrl: String? = {quoted(identity.source_release_url) if identity.source_release_url else "null"}
}}
'''
    xcconfig = f'''// Generated by tools/generate_app_identity.py from app.properties.
LOGISIM_DISPLAY_NAME = {identity.name}
MARKETING_VERSION = {identity.version}
CURRENT_PROJECT_VERSION = {identity.build}
PRODUCT_BUNDLE_IDENTIFIER = {identity.apple_id}
'''
    metadata = {
        "name": identity.name, "version": identity.version, "build": identity.build,
        "androidApplicationId": identity.android_id, "appleBundleIdentifier": identity.apple_id,
        "repository": identity.repository, "upstream": identity.upstream,
        "sourceReleaseUrl": identity.source_release_url,
        "relationship": "Independent Kotlin Multiplatform port derived from Logisim Evolution; not an official upstream release.",
        "artifactStem": f"LogisimMobile-{identity.version}-{identity.build}",
    }
    return {
        "composeApp/src/commonMain/kotlin/dev/logisim/mobile/AppIdentity.kt": kotlin.encode(),
        "iosApp/Config/Identity.xcconfig": xcconfig.encode(),
        "docs/releases/app-identity.json": (json.dumps(metadata, ensure_ascii=False, indent=2) + "\n").encode(),
    }


def generate(root: Path, check: bool) -> bool:
    failures = []
    for relative, contents in generated_files(read_identity(root / "app.properties")).items():
        target = root / relative
        if check:
            if not target.is_file() or target.read_bytes() != contents:
                failures.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(contents)
    if failures:
        print("Generated application identity is stale: " + ", ".join(failures), file=sys.stderr)
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    try:
        return 0 if generate(ROOT, options.check) else 1
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
