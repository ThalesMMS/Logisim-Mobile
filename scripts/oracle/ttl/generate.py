#!/usr/bin/env python3
"""Generate the pin catalog and per-model fixtures from desktop oracle observations."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('metadata', type=Path)
parser.add_argument('combinational', type=Path)
parser.add_argument('sequential', type=Path)
parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[3])
args = parser.parse_args()
metadata = {}
lines = ['package dev.logisim.mobile.core', '', '/** Physical pin metadata from the desktop TTL catalog. Generated by scripts/oracle/ttl. */', 'object TtlCatalog {', '    val specs: List<TtlChipSpec> = listOf(']
for line in args.metadata.read_text().splitlines():
    model, count, gnd, vcc, height, outputs, io, unused, names = line.split('\t')
    omit = {int(gnd), int(vcc)} | {int(i) for i in unused.split(',') if i}
    pins = [i for i in range(1, int(count) + 1) if i not in omit]
    outputs_set = {int(i) for i in outputs.split(',') if i}
    metadata[model] = len([i for i in pins if i not in outputs_set])
    def set_literal(value):
        return 'setOf(' + value + ')' if value else 'emptySet()'
    pairs = zip(pins, names.split('|')) if names else []
    labels = ', '.join(str(i) + ' to ' + json.dumps(name, ensure_ascii=False) for i, name in pairs)
    lines.append(f'        TtlChipSpec("{model}", {count}, {set_literal(outputs)}, {set_literal(io)}, {set_literal(unused)}, mapOf({labels}), {gnd}, {vcc}, {height}),')
lines += ['    )', '    private val byModel = specs.associateBy { it.model }', '    fun spec(model: String): TtlChipSpec = byModel[model] ?: error("TTL desconhecido: $model")', '}']
(args.root / 'core/src/commonMain/kotlin/dev/logisim/mobile/core/TtlCatalog.kt').write_text('\n'.join(lines) + '\n')
fixture_dir = args.root / 'core/src/jvmTest/resources/ttl-fixtures'
fixture_dir.mkdir(parents=True, exist_ok=True)
for source, mode in [(args.combinational, 'combinational'), (args.sequential, 'sequential')]:
    grouped = {}
    for line in source.read_text().splitlines():
        grouped.setdefault(line.split('\t', 1)[0], []).append(line)
    for model, rows in grouped.items():
        if mode == 'sequential':
            selected = rows
        else:
            binary = min(1 << metadata[model], 4096)
            indexes = {0, binary - 1}
            indexes.update(1 << i for i in range(min(metadata[model], 12)))
            indexes.update(range(binary, min(binary + 4, len(rows))))
            indexes.update(range(binary + 256, min(binary + 272, len(rows))))
            selected = [row for i, row in enumerate(rows) if i in indexes]
        (fixture_dir / f'{model}.tsv').write_text(f'# {mode}\n' + '\n'.join(selected) + '\n')
print(f'Generated {len(metadata)} models and their fixtures')
