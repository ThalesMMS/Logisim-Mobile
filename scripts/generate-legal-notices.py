#!/usr/bin/env python3
"""Generate bundled legal notices from pinned licenses and resolved production dependencies."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = {"m": "http://maven.apache.org/POM/4.0.0"}
GENERATED = ROOT / "composeApp/src/commonMain/kotlin/dev/logisim/mobile/LegalNoticeContent.kt"


def pom_metadata(path: Path, seen: set[Path] | None = None) -> tuple[list[dict], str]:
    seen = set() if seen is None else seen
    if path in seen:
        raise ValueError(f"Cyclic Maven parent: {path.name}")
    seen.add(path)
    xml = ET.parse(path).getroot()
    licenses = [{"name": item.findtext("m:name", default="", namespaces=NS),
                 "url": item.findtext("m:url", default="", namespaces=NS)}
                for item in xml.findall("m:licenses/m:license", NS)]
    url = xml.findtext("m:url", default="", namespaces=NS)
    parent = xml.find("m:parent", NS)
    if parent is not None and (not licenses or not url):
        parts = [parent.findtext(f"m:{key}", namespaces=NS) for key in ("groupId", "artifactId", "version")]
        if all(parts):
            directory = path.parents[4].joinpath(*parts)
            candidates = sorted(directory.glob("*/*.pom"))
            if candidates:
                inherited, parent_url = pom_metadata(candidates[0], seen)
                licenses = licenses or inherited
                url = url or parent_url
    return licenses, url


def refresh(input_path: Path) -> None:
    raw = json.loads(input_path.read_text())
    if raw.get("schemaVersion") != 1:
        raise ValueError("Unsupported Gradle dependency inventory schema")
    dependencies = []
    for row in raw["dependencies"]:
        if not row.get("pom"):
            raise ValueError(f"Missing POM for {row['coordinate']}")
        pom = Path(row["pom"])
        licenses, url = pom_metadata(pom)
        if not licenses:
            raise ValueError(f"Missing license for {row['coordinate']}")
        for license_info in licenses:
            if "apache" not in license_info["name"].lower():
                raise ValueError(f"Review and bundle newly introduced license: {row['coordinate']}: {license_info}")
        dependencies.append({"coordinate": row["coordinate"],
                             "configurations": sorted(row["configurations"]),
                             "license": "Apache-2.0", "declaredLicenses": licenses,
                             "projectUrl": url,
                             "pomSha256": hashlib.sha256(pom.read_bytes()).hexdigest()})
    (ROOT / "legal/runtime-dependencies.json").write_text(json.dumps({
        "schemaVersion": 1,
        "configurations": ["androidRuntimeClasspath", "iosArm64CompileKlibraries", "iosSimulatorArm64CompileKlibraries"],
        "dependencies": sorted(dependencies, key=lambda item: item["coordinate"]),
    }, indent=2, ensure_ascii=False) + "\n")


def outputs() -> dict[Path, str]:
    inventory = json.loads((ROOT / "legal/runtime-dependencies.json").read_text())
    provenance = json.loads((ROOT / "legal/provenance.json").read_text())
    coordinates = [item["coordinate"] for item in inventory["dependencies"]]
    lines = ["# Third-party notices", "", "Generated by `python3 scripts/generate-legal-notices.py`.", "",
             "## Project and source provenance", ""]
    for item in provenance["sources"]:
        lines += [f"### {item['title']}", "", item["notice"], "",
                  f"License: `{item['license']}`. Source: {item['source']}", ""]
    lines += ["## Resolved runtime dependencies", "",
              "The following Maven components are resolved for Android or iOS production code. "
              "Native dependencies embedded by Skiko are listed separately in `legal/provenance.json`.", "",
              "| Component | License | Platforms |", "| --- | --- | --- |"]
    for item in inventory["dependencies"]:
        platforms = sorted({"Android" if configuration.startswith("android") else "iOS" for configuration in item["configurations"]})
        lines.append(f"| `{item['coordinate']}` | {item['license']} | {', '.join(platforms)} |")
    lines += ["", "License texts are in `legal/licenses/`. The application bundles the same texts and notices.", ""]
    notices = []
    for item in provenance["sources"]:
        text = item["notice"] + "\n\nSource: " + item["source"]
        for license_file in item.get("licenseFiles", []):
            text += "\n\n" + Path(license_file).name + "\n\n" + (ROOT / license_file).read_text()
        notices.append((item["title"], text))
    notices.append(("Runtime dependencies", "Apache-2.0 Maven components resolved for Android and iOS:\n\n" +
                    "\n".join(coordinates) + "\n\n" + (ROOT / "legal/licenses/Apache-2.0.txt").read_text()))
    kotlin = ["package dev.logisim.mobile", "", "// Generated by scripts/generate-legal-notices.py.",
              "internal data class LegalNotice(val title: String, val text: String)", "",
              "internal object LegalNoticeContent {", "    val notices: List<LegalNotice> = listOf("]
    for title, text in notices:
        chunks = [json.dumps(text[index:index + 8000], ensure_ascii=False).replace("$", "\\$")
                  for index in range(0, len(text), 8000)]
        kotlin += [f"        LegalNotice({json.dumps(title, ensure_ascii=False)}, listOf("]
        kotlin += ["            " + chunk + "," for chunk in chunks]
        kotlin += ["        ).joinToString(\"\")),"]
    kotlin += ["    )", "}", ""]
    return {ROOT / "THIRD_PARTY_NOTICES.md": "\n".join(lines), GENERATED: "\n".join(kotlin)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", type=Path, help="Resolved Gradle JSON from exportLegalRuntimeDependencies")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.refresh:
        refresh(args.refresh)
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Regenerate legal notices: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Legal notices match the resolved dependency inventory.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
