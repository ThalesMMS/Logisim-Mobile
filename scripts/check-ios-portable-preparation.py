#!/usr/bin/env python3
"""Compile and execute isolated portable-evidence checks; never builds or launches an app."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def run(command):
    result = subprocess.run([str(value) for value in command], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f"Offline command failed ({result.returncode}): {command[0]}\n{result.stdout}{result.stderr}")
    return result.stdout.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--harness-root", type=Path, default=ROOT,
                        help="Checkout containing the current NativeUIHarness and NativeFilesDestinationNavigator")
    parser.add_argument("--core-snapshot", type=Path,
                        help="Optional offline workspace generated by the owning Kotlin core, with existing catalog.lock")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    harness = args.harness_root.resolve()
    developer = Path(run(["xcode-select", "-p"]))
    sdk = Path(run(["xcrun", "--sdk", "iphonesimulator", "--show-sdk-path"]))
    platform = developer / "Platforms/iPhoneSimulator.platform/Developer"
    sources = [harness / "scripts/ios_native_ui/NativeUIHarness.swift",
               harness / "scripts/ios_e2e_ui/ClipboardReceiverUI.swift",
               harness / "scripts/ios_e2e_ui/ObservedProjectXML.swift",
               harness / "scripts/ios_e2e_ui/NativeFilesDestinationNavigator.swift",
               ROOT / "scripts/ios_e2e_ui/PortableWorkspaceEvidence.swift",
               ROOT / "scripts/ios_e2e_ui/PortableProjectEndToEndTests.swift"]
    for source in sources:
        if not source.is_file():
            raise ValueError(f"Required reviewed native harness source is missing: {source}; pass --harness-root")
    checks = ROOT / "scripts/portable/PortableWorkspaceEvidenceChecks.swift"
    source_bytes = {source: source.read_bytes() for source in [*sources, checks]}
    harness_pin = run(["git", "-C", harness, "rev-parse", "HEAD"])
    with tempfile.TemporaryDirectory(prefix="portable-ios-offline-") as temporary:
        directory = Path(temporary)
        frozen = []
        for source, content in source_bytes.items():
            copy = directory / source.name
            copy.write_bytes(content)
            frozen.append(copy)
        run(["xcrun", "swiftc", "-typecheck", "-target", "arm64-apple-ios17.0-simulator", "-sdk", sdk,
             "-F", platform / "Library/Frameworks", "-I", platform / "usr/lib", *frozen[:-1]])
        executable = directory / "checks"
        run(["xcrun", "swiftc", frozen[-3], frozen[-1], "-o", executable])
        command = [executable, directory / "checks.json"]
        if args.core_snapshot:
            command.append(args.core_snapshot.resolve())
        run(command)
        receipt = json.loads((directory / "checks.json").read_text())
    receipt.update({"typecheck": {"status": "PASSED", "target": "arm64-apple-ios17.0-simulator", "sdk": sdk.name},
                    "swift": run(["xcrun", "swiftc", "--version"]),
                    "harnessSourcePin": harness_pin,
                    "sources": {str(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path.relative_to(harness)):
                                hashlib.sha256(content).hexdigest() for path, content in source_bytes.items()},
                    "productionChanges": False, "nativeUiStatus": "NOT_RUN"})
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(receipt, indent=2) + "\n")
    print(args.output.resolve())


if __name__ == "__main__":
    main()
