#!/usr/bin/env python3
"""Embed the reviewed desktop temporal corpus for common JVM and Native tests."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "examples/corpus/temporal"
TARGET = ROOT / "core/src/commonTest/kotlin/dev/logisim/mobile/core/TemporalOracleCases.kt"


def generated():
    rows = ["// Generated by scripts/generate-temporal-fixtures.py. Do not edit.",
            "package dev.logisim.mobile.core", "", "internal data class TemporalOracleCase(",
            "    val id: String, val xml: String, val operations: String, val expected: String,", ")", "",
            "internal val temporalOracleCases = listOf("]
    fixtures = sorted(DIRECTORY.glob("*.circ"))
    if not fixtures:
        raise ValueError("No temporal circuit fixtures")
    for fixture in fixtures:
        values = [fixture.stem, fixture.read_text(), fixture.with_suffix(".ops.tsv").read_text(),
                  fixture.with_suffix(".desktop.tsv").read_text()]
        rows.append("    TemporalOracleCase(")
        for value in values:
            assert '"""' not in value and "$" not in value
            rows.append('        """' + value.rstrip() + '""",')
        rows.append("    ),")
    rows += [")", ""]
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != content:
            raise SystemExit("Temporal corpus is stale. Run python3 scripts/generate-temporal-fixtures.py")
    else:
        TARGET.write_text(content)


if __name__ == "__main__":
    main()
