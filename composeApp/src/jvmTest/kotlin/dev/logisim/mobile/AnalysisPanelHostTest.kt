    @Test
    fun fullAdderTableAndExpressionsFollowTheCircuit() = runDesktopComposeUiTest(390, 844) {
        val host = Host(adder)
        show(host)
        readCircuit()
        screenshot("phone-07-table")
        click("Expressions")
        // The expressions are derived off the main thread; capture the view either way, then check it.
        runCatching { waitUntil(timeoutMillis = 10_000) { expressionText().contains("Cout") } }
        screenshot("phone-08-expressions")
        val text = expressionText()
        assertTrue("S :=" in text && "Cout :=" in text && "Y := A & B" !in text, text)
        // The unedited text is the table itself: nothing to apply until it changes, and the table's own
        // expressions come back on request.
        onNodeWithText("Apply to table").assertIsNotEnabled()
        expressionField().performTextReplacement("S := A ^ B")
        waitForIdle()
        onNodeWithText("Apply to table").assertIsEnabled()
        click("Show the table's expressions")
        waitUntil(timeoutMillis = 10_000) { expressionText() == text }
        onNodeWithText("Apply to table").assertIsNotEnabled()
        // A name that is not an input is refused, as in Evolution, instead of becoming a new input.
        expressionField().performTextReplacement("Cout := A & B | S")
        waitForIdle()
        click("Apply to table")
        waitUntil(timeoutMillis = 10_000) { !absent("“S” is not an input variable.") }
        click("Table")
        assertFalse(exists("analysis-cell-0-5"))
    }

