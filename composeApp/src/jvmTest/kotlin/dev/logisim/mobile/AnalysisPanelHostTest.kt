/**
 * Combinational analysis in its tool sheet at phone sizes (390x844 portrait, 844x390 landscape): the table survives
 * dismissal, replacements ask first and can be undone, columns are added, removed and moved without typing, the
 * expressions follow the table, and every view scrolls. Screenshots go to `-PuiScreenshots=<dir>`.
 */
@OptIn(ExperimentalTestApi::class)
class AnalysisPanelHostTest {
    /** A full adder generated by the app itself, so the pins and gates match what Read circuit expects. */
    private val adder: CircuitProject = CircuitProject(listOf(AnalysisCircuitGenerator.generateExpressions(
        listOf("A", "B", "Cin"),
        linkedMapOf(
            "S" to BooleanExpressionParser.parse("A ^ B ^ Cin"),
            "Cout" to BooleanExpressionParser.parse("A & B | Cin & (A ^ B)"),
        ),
        name = "Adder",
    )))

    private class FakeClipboard : ClipboardManager {
        var content: AnnotatedString? = null
        override fun setText(annotatedString: AnnotatedString) { content = annotatedString }
        override fun getText(): AnnotatedString? = content
    }

    /** Table files whose picker never answers: an Import stays running until it is cancelled. */
    private class PendingTableFiles : DocumentAssetActions {
        var selections = 0
        override val analysisTables = object : AnalysisTableFiles {
            override fun select(onResult: (AnalysisTableSelection) -> Unit) { selections++ }
            override fun createSpoolFile(): AnalysisSpoolFile = error("No file is read")
        }
        override fun open(mimeTypes: List<String>, maximumBytes: Int, onResult: (AssetOpenResult) -> Unit) = Unit
        override fun create(asset: DocumentAsset, onResult: (AssetActionResult) -> Unit) = Unit
        override fun share(asset: DocumentAsset, onResult: (AssetActionResult) -> Unit) = Unit
        override fun printPdf(asset: DocumentAsset, onResult: (AssetActionResult) -> Unit) = Unit
    }

    private class Host(
        project: CircuitProject,
        assets: DocumentAssetActions? = null,
        private val access: EditorProjectAccess = EditorProjectAccess.EDITABLE,
    ) {
        val tool = analysisEditorTool(ComponentCatalog.registry, assets = assets)
        val notices = mutableListOf<LocalizedText>()
        val clipboard = FakeClipboard()
        var open by mutableStateOf(true)
        var context by mutableStateOf(context(project, 1L))

        fun context(project: CircuitProject, identity: Long) = EditorToolContext(
            project, project.circuits.first(), SimulationState(), emptyList(), {}, {}, {}, {}, {},
            documentIdentity = identity, showNotice = { notices += it }, projectExports = ProjectGraphExportPolicy(access),
        )
    }

    /** The tool sheet as App.kt lays it out: a 700 dp cap, the sheet title with Close, then the tool content. */
    private fun ComposeUiTest.show(host: Host, language: AppLanguage = AppLanguage.ENGLISH) {
        setContent {
            CompositionLocalProvider(LocalAppLanguage provides language, LocalClipboardManager provides host.clipboard) {
                LogisimTheme(dark = false) {
                    Surface(Modifier.fillMaxSize()) {
                        host.tool.runtime(host.context)
                        if (host.open) EditorModalSheet(onDismissRequest = { host.open = false },
                            modifier = Modifier.testTag("editor-tool-sheet")) {
                            BoxWithConstraints(Modifier.fillMaxWidth().heightIn(max = 700.dp)) {
                                Row(Modifier.fillMaxWidth().padding(horizontal = 12.dp)) {
                                    Column(Modifier.weight(1f).padding(vertical = 12.dp)) {
                                        Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                                            Text(host.tool.titleText.resolve(language), Modifier.weight(1f), fontWeight = FontWeight.Bold)
                                            TextButton(onClick = { host.open = false }, modifier = Modifier.testTag("editor-tool-close")) {
                                                Text("Close")
                                            }
                                        }
                                        key(host.tool.id, host.context.documentIdentity) { host.tool.content(host.context) }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        waitForIdle()
    }

    private fun ComposeUiTest.description(tag: String): String =
        onNodeWithTag(tag, useUnmergedTree = true).fetchSemanticsNode().config.getOrNull(SemanticsProperties.ContentDescription)
            ?.joinToString().orEmpty()

    /** The value TalkBack reads after the cell's position: its state description. */
    private fun ComposeUiTest.state(tag: String): String =
        onNodeWithTag(tag, useUnmergedTree = true).fetchSemanticsNode().config.getOrNull(SemanticsProperties.StateDescription).orEmpty()

    private fun ComposeUiTest.exists(tag: String) = onAllNodesWithTag(tag, useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty()

    private fun ComposeUiTest.click(text: String) {
        onNodeWithText(text).performClick()
        waitForIdle()
    }

    private fun ComposeUiTest.clickCell(tag: String) {
        onNodeWithTag(tag, useUnmergedTree = true).performClick()
        waitForIdle()
    }

    /** Brings a table row into the lazy list (rows off-screen are not composed). */
    private fun ComposeUiTest.scrollTo(tag: String) {
        onNodeWithTag("analysis-table").performScrollToNode(hasTestTag(tag))
        waitForIdle()
    }

    private fun ComposeUiTest.isDisplayed(node: SemanticsNodeInteraction) = runCatching { node.assertIsDisplayed() }.isSuccess

