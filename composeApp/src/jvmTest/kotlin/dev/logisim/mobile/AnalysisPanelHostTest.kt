    private fun ComposeUiTest.operatorScenario(shot: String) {
        val host = Host(adder)
        show(host)
        createTable("A, B", "Y")
        click("Expressions")
        expressionField().performTextReplacement("Y := A B")
        waitForIdle()
        expressionField().performTextInputSelection(androidx.compose.ui.text.TextRange(6))
        waitForIdle()
        onNodeWithContentDescription("Insert AND").assertHeightIsAtLeast(48.dp).assertWidthIsAtLeast(48.dp).performClick()
        waitForIdle()
        assertEquals("Y := A& B", expressionText())
        // The cursor follows the inserted operator: the next one goes after it.
        onNodeWithContentDescription("Insert NOT").performClick()
        waitForIdle()
        assertEquals("Y := A&~ B", expressionText())
        // A selection is replaced.
        expressionField().performTextInputSelection(androidx.compose.ui.text.TextRange(6, 8))
        waitForIdle()
        onNodeWithContentDescription("Insert XOR").performClick()
        waitForIdle()
        assertEquals("Y := A^ B", expressionText())
        for (name in listOf("Insert OR", "Insert opening parenthesis", "Insert closing parenthesis", "Insert 0", "Insert 1")) {
            onNodeWithContentDescription(name).assertHeightIsAtLeast(48.dp)
        }
        screenshot(shot)
        // Inserting is an edit: the result can be applied.
        onNodeWithText("Apply to table").assertIsEnabled()
    }

