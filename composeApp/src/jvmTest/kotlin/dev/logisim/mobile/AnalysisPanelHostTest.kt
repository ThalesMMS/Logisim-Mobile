        // An earlier, smaller table whose expressions were shown and edited.
        session.load(dev.logisim.mobile.core.TruthTable(listOf("A", "B"), listOf("S"),
            List(4) { listOf(if (it == 1 || it == 2) TruthCell.ONE else TruthCell.ZERO) }))
        session.expressionText = "S := A ^ B"
        session.expressionsEdited = true
        val spool = object : AnalysisTableSpool {
            override fun append(record: ByteArray) = Unit
            override fun seal() = Unit
            override fun read(index: Int, record: ByteArray) = record.fill(0x01)
            override fun close() = Unit
