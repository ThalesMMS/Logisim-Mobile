#!/usr/bin/env python3
"""Generate the shared example catalog from the same XML files users can open."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "core/src/commonMain/kotlin/dev/logisim/mobile/core/BundledCircuitExamples.kt"


def quoted(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def mapping(values):
    return "mapOf(" + ", ".join(f"{quoted(k)} to {quoted(v)}" for k, v in values.items()) + ")"


def actions(values):
    return "listOf(" + ",\n".join(
        "ExampleAction(" + ", ".join((quoted(a["name"]), mapping(a.get("inputs", {})),
                                       str(a.get("ticks", 0)), mapping(a.get("expected", {})))) + ")"
        for a in values) + ")"


def generate():
    raw = (ROOT / "examples/catalog.json").read_bytes()
    catalog = json.loads(raw)
    assert catalog["schemaVersion"] == 1
    ids = set()
    rows = []
    digest = hashlib.sha256(raw)
    for example in catalog["examples"]:
        assert example["id"] not in ids, "Duplicate example ID"
        ids.add(example["id"])
        path = (ROOT / example["path"]).resolve()
        assert path.is_relative_to(ROOT) and path.suffix == ".circ"
        data = path.read_bytes()
        digest.update(example["path"].encode() + b"\0" + data)
        probes = "listOf(" + ", ".join(f"ExampleProbe({quoted(p['id'])}, GridPoint({p['x']}, {p['y']}), {p['width']})"
                                       for p in example["probes"]) + ")"
        rows.append("CircuitExample(" + ",\n".join((quoted(example["id"]), quoted(example["title"]),
                    quoted(example["category"]), quoted(data.decode()), probes,
                    actions(example.get("startup", [])), actions(example["actions"]))) + ")")
    return "\n".join((
        "// Generated by scripts/generate_examples.py from examples/catalog.json and .circ files.",
        "package dev.logisim.mobile.core", "", "internal object BundledCircuitExamples {",
        f"    const val sourceHash = {quoted(digest.hexdigest())}",
        "    val all = listOf(\n" + ",\n".join(rows) + "\n    )", "}", ""))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != source:
            raise SystemExit("Generated example catalog is stale; run scripts/generate_examples.py")
    else:
        TARGET.write_text(source)
    print("Example catalog matches its source fixtures.")


if __name__ == "__main__":
    main()
